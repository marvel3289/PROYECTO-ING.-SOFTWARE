-- PROYECTO INTEGRADOR: Biblioteca San Lucas Sacatepéquez
-- Fase 1, paso 4: tablas PostgreSQL.
-- Ejecutar solamente en la conexión 'biblioteca_san_lucas'.
-- Seguridad: el bloque verifica la base antes de crear cualquier objeto.
-- No incluye DROP, TRUNCATE, DELETE, UPDATE ni INSERT.
-- En DBeaver, ejecutar el bloque DO completo con Alt+X (ejecutar script).

DO $biblioteca$
BEGIN
    IF current_database() <> 'biblioteca_san_lucas' THEN
        RAISE EXCEPTION 'OPERACIÓN CANCELADA: conectado a %, no a biblioteca_san_lucas', current_database();
    END IF;

    CREATE TABLE IF NOT EXISTS public.usuarios (
        id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre           varchar(150) NOT NULL,
        correo           varchar(254) NOT NULL UNIQUE,
        sal              varchar(64) NOT NULL,
        hash_contrasena  varchar(128) NOT NULL,
        rol              varchar(20) NOT NULL,
        activo           boolean NOT NULL DEFAULT true,
        creado_en        timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMINISTRADOR', 'OPERADOR', 'LECTOR')),
        CONSTRAINT ck_usuarios_nombre CHECK (length(btrim(nombre)) > 0)
    );

    CREATE TABLE IF NOT EXISTS public.libros (
        id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        titulo           varchar(300) NOT NULL,
        autor            varchar(200) NOT NULL,
        isbn             varchar(32) NOT NULL UNIQUE
    );

    CREATE TABLE IF NOT EXISTS public.ejemplares (
        id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        libro_id         integer NOT NULL REFERENCES public.libros(id) ON DELETE RESTRICT,
        codigo           varchar(60) NOT NULL UNIQUE,
        disponible       boolean NOT NULL DEFAULT true
    );

    CREATE TABLE IF NOT EXISTS public.prestamos (
        id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        usuario_id       integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
        ejemplar_id      integer NOT NULL REFERENCES public.ejemplares(id) ON DELETE RESTRICT,
        fecha_prestamo   date NOT NULL,
        fecha_vencimiento date NOT NULL,
        fecha_devolucion date,
        CONSTRAINT ck_prestamos_vencimiento CHECK (fecha_vencimiento >= fecha_prestamo),
        CONSTRAINT ck_prestamos_devolucion CHECK (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_prestamo)
    );

    -- Impide préstamos simultáneos del mismo ejemplar mientras no se registre devolución.
    CREATE UNIQUE INDEX IF NOT EXISTS ux_prestamos_ejemplar_activo
        ON public.prestamos(ejemplar_id) WHERE fecha_devolucion IS NULL;

    CREATE INDEX IF NOT EXISTS ix_prestamos_usuario ON public.prestamos(usuario_id);
END;
$biblioteca$;

